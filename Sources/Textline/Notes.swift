import AppKit
import SwiftUI
import Combine
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

struct Note: Identifiable, Codable, Equatable {
    var id = UUID()
    let text: String
    var tilt = Double.random(in: -2.5...2.5)
    var imageFile: String? = nil
    var imageHash: String? = nil
    var title: String? = nil
    var remark: String? = nil
    var tags: [String]? = nil
    var hasAnnotation: Bool { title != nil || remark != nil || !(tags ?? []).isEmpty }
    var tooltip: String {
        var parts: [String] = []
        if let title { parts.append(title) }
        if let remark { parts.append("备注：" + remark) }
        if let tags, !tags.isEmpty { parts.append(tags.map { "#" + $0 }.joined(separator: " ")) }
        parts.append(imageFile == nil ? String(text.prefix(4000)) : "拖到其他窗口使用 · 右键编辑标注或复制")
        return parts.joined(separator: "\n\n")
    }
}

struct DeletedEntry: Codable {
    let note: Note
    let index: Int
}
struct DeletionStep: Codable {
    let id: UUID
    var entries: [DeletedEntry]
}

@MainActor final class Notes: ObservableObject {
    @Published var items: [Note] = []
    @Published var revealed = false
    @Published var copied: UUID?
    @Published var scrollGeneration = 0
    var itemFrames: [UUID: CGRect] = [:]
    @Published var paused = false
    @Published var storageError: String?
    @Published private(set) var removed = Set<UUID>()
    @Published private(set) var restoring = Set<UUID>()
    @Published private(set) var canUndo = false
    private var undoStep: DeletionStep?
    private var pendingClears = Set<UUID>()
    private var undoFile: URL { file.deletingLastPathComponent().appendingPathComponent("last-deletion.json") }
    var onRemove: ((Note) -> Bool)?
    var onNew: (() -> Void)?
    private let board: NSPasteboard
    private var lastCount: Int
    private let file: URL
    private let thumbs = NSCache<NSString, NSImage>()
    private var folder: URL { file.deletingLastPathComponent().appendingPathComponent("Images") }
    init(board: NSPasteboard = .general, file: URL? = nil) {
        self.board = board
        lastCount = board.changeCount
        self.file = file ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Textline/history.json")
        if let data = try? Data(contentsOf: self.file), let saved = try? JSONDecoder().decode([Note].self, from: data) {
            items = Array(saved.filter { note in
                guard let path = note.imageFile else { return true }
                return path == URL(fileURLWithPath: path).lastPathComponent && FileManager.default.fileExists(atPath: self.folder.appendingPathComponent(path).path)
            }.prefix(100))
        }
        if let data = try? Data(contentsOf: undoFile), var saved = try? JSONDecoder().decode(DeletionStep.self, from: data) {
            saved.entries = saved.entries.filter { entry in
                !items.contains(where: { $0.id == entry.note.id }) && (entry.note.imageFile == nil || imageURL(entry.note).map { FileManager.default.fileExists(atPath: $0.path) } == true)
            }
            if !saved.entries.isEmpty { undoStep = saved; canUndo = true }
        }
        thumbs.countLimit = 100
    }
    func poll() {
        let count = board.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard !paused, let entries = board.pasteboardItems, !entries.isEmpty else { return }
        let ignored = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url"]
        guard entries.allSatisfy({ entry in !ignored.contains(where: { entry.types.contains(.init($0)) }) }) else { return }
        // Documents often include image representations alongside copied text.
        // Prefer text when both are available, so a single copy hangs once.
        if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard text.utf8.count <= 1_048_576, board.changeCount == count else { return }
            hang(text)
        } else if let type = board.availableType(from: [.png, .tiff]), let data = board.data(forType: type), board.changeCount == count {
            _ = hangImage(data)
        }
    }
    func hang(_ text: String) {
        if let i = items.firstIndex(where: { $0.imageFile == nil && $0.text == text }) {
            let note = items.remove(at: i); items.insert(note, at: 0)
        } else { items.insert(Note(text: text), at: 0) }
        finishHang()
    }
    @discardableResult func hangImage(_ data: Data, notify: Bool = true) -> Bool {
        guard data.count <= 32 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let info = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = info[kCGImagePropertyPixelWidth] as? Int, let h = info[kCGImagePropertyPixelHeight] as? Int,
              w > 0, h > 0, w <= 40_000_000 / h,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let png = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]) else { return false }
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        if let i = items.firstIndex(where: { $0.imageHash == hash }) {
            // Folder and clipboard can report the same screenshot. Keep its position.
            return items[i].imageFile != nil
        }
        let name = UUID().uuidString + ".png"
        let url = folder.appendingPathComponent(name)
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try png.write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            items.insert(Note(text: "", imageFile: name, imageHash: hash), at: 0)
            finishHang(notify: notify)
            return true
        } catch { storageError = "图片暂未保存：\(error.localizedDescription)"; return false }
    }
    func imageURL(_ note: Note) -> URL? {
        guard let name = note.imageFile, name == URL(fileURLWithPath: name).lastPathComponent else { return nil }
        return folder.appendingPathComponent(name)
    }
    func thumbnail(_ note: Note) -> NSImage? {
        guard let url = imageURL(note) else { return nil }
        if let cached = thumbs.object(forKey: note.id.uuidString as NSString) { return cached }
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 420, kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height))
        thumbs.setObject(image, forKey: note.id.uuidString as NSString)
        return image
    }
    private func finishHang(notify: Bool = true) {
        settleRemovals()
        let removed = Array(items.dropFirst(100)); items = Array(items.prefix(100))
        scrollGeneration += 1
        if save() { removed.forEach(deleteImage) }
        if notify { onNew?() }
    }
    func dragProvider(_ note: Note) -> NSItemProvider {
        guard let url = imageURL(note) else { return NSItemProvider(object: note.text as NSString) }
        guard let data = try? Data(contentsOf: url) else {
            storageError = "无法读取图片"; return NSItemProvider()
        }
        // File representation for file drop targets; PNG pixels for image drop targets.
        let provider = NSItemProvider(contentsOf: url) ?? NSItemProvider()
        provider.suggestedName = (note.title ?? "拾片图片") + ".png"
        provider.registerDataRepresentation(forTypeIdentifier: UTType.png.identifier, visibility: .all) { completion in
            completion(data, nil); return nil
        }
        return provider
    }
    func copy(_ note: Note) {
        if let url = imageURL(note) {
            guard let data = try? Data(contentsOf: url) else { storageError = "无法读取图片"; return }
            board.clearContents(); board.setData(data, forType: .png)
        } else { board.clearContents(); board.setString(note.text, forType: .string) }
        lastCount = board.changeCount
        copied = note.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.copied == note.id { self?.copied = nil }
        }
    }
    func openImage(_ note: Note) { if let url = imageURL(note) { NSWorkspace.shared.open(url) } }
    func exportImage(_ note: Note) {
        guard let source = imageURL(note) else { return }
        let dialog = NSSavePanel(); dialog.nameFieldStringValue = "拾片.png"; dialog.allowedContentTypes = [.png]
        NSApp.activate(ignoringOtherApps: true)
        if dialog.runModal() == .OK, let target = dialog.url {
            do { try Data(contentsOf: source).write(to: target, options: .atomic) }
            catch { storageError = "保存失败：\(error.localizedDescription)" }
        }
    }
    private func deleteImage(_ note: Note) {
        guard undoStep?.entries.contains(where: { $0.note.id == note.id }) != true else { return }
        thumbs.removeObject(forKey: note.id.uuidString as NSString)
        if let url = imageURL(note) { try? FileManager.default.removeItem(at: url) }
    }
    @discardableResult func annotate(_ id: UUID, title: String, remark: String, tags: String) -> Bool {
        guard let index = items.firstIndex(where: { $0.id == id }), !removed.contains(id) else {
            storageError = "这条内容已被取下，无法保存标注"; return false
        }
        func clean(_ value: String) -> String? {
            let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
            return trimmed.isEmpty ? nil : trimmed
        }
        var unique: [String] = []
        for part in tags.components(separatedBy: CharacterSet(charactersIn: ",，;；\n")) {
            if let tag = clean(part)?.trimmingCharacters(in: CharacterSet(charactersIn: "#")), !tag.isEmpty, !unique.contains(tag) { unique.append(tag) }
        }
        items[index].title = clean(title); items[index].remark = clean(remark)
        items[index].tags = unique.isEmpty ? nil : unique
        return save()
    }
    @discardableResult private func persistUndo(_ step: DeletionStep?) -> Bool {
        do {
            if let step {
                try FileManager.default.createDirectory(at: undoFile.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
                try JSONEncoder().encode(step).write(to: undoFile, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: undoFile.path)
            } else if FileManager.default.fileExists(atPath: undoFile.path) {
                try FileManager.default.removeItem(at: undoFile)
            }
            return true
        } catch { storageError = "撤销记录暂未保存：\(error.localizedDescription)"; return false }
    }
    func remove(_ note: Note, step: UUID = UUID(), originalIndex: Int? = nil) {
        guard let index = items.firstIndex(where: { $0.id == note.id }), !removed.contains(note.id) else { return }
        let previous = undoStep
        var next = previous?.id == step ? previous! : DeletionStep(id: step, entries: [])
        next.entries.append(DeletedEntry(note: note, index: originalIndex ?? index))
        guard persistUndo(next) else { return }
        undoStep = next; canUndo = true
        let animated = onRemove?(note) == true
        if animated { removed.insert(note.id) }
        else { items.removeAll { $0.id == note.id } }
        if save(), let previous, previous.id != step {
            pendingClears.remove(previous.id)
            for entry in previous.entries where !items.contains(where: { $0.id == entry.note.id && !removed.contains($0.id) }) { deleteImage(entry.note) }
        }
    }
    func settleRemovals() {
        guard !removed.isEmpty else { return }
        items.removeAll { removed.contains($0.id) }; removed.removeAll()
    }
    func clear() {
        let old = Array(items.enumerated()).filter { !removed.contains($0.element.id) }
        guard !old.isEmpty else { return }
        let step = UUID()
        if onRemove == nil {
            for (index, note) in old { remove(note, step: step, originalIndex: index) }
            return
        }
        pendingClears.insert(step)
        for (order, entry) in old.enumerated() {
            DispatchQueue.main.asyncAfter(deadline: .now() + Double(order) * 0.06) { [weak self] in
                guard let self, self.pendingClears.contains(step) else { return }
                self.remove(entry.element, step: step, originalIndex: entry.offset)
                if order == old.count - 1 { self.pendingClears.remove(step) }
            }
        }
    }
    func undoDelete() {
        guard let step = undoStep else { return }
        let oldItems = items, oldRemoved = removed, oldRestoring = restoring
        var restored = items.filter { !removed.contains($0.id) }
        let restoredIDs = Set(step.entries.map { $0.note.id })
        var evicted: [Note] = []
        for entry in step.entries.sorted(by: { $0.index < $1.index }) where !restored.contains(where: { $0.id == entry.note.id }) {
            let duplicates = restored.filter {
                ($0.imageFile == nil && entry.note.imageFile == nil && $0.text == entry.note.text) ||
                ($0.imageHash != nil && $0.imageHash == entry.note.imageHash)
            }
            evicted.append(contentsOf: duplicates)
            let duplicateIDs = Set(duplicates.map(\.id))
            restored.removeAll { duplicateIDs.contains($0.id) }
            restored.insert(entry.note, at: min(entry.index, restored.count))
        }
        while restored.count > 100, let index = restored.lastIndex(where: { !restoredIDs.contains($0.id) }) { evicted.append(restored.remove(at: index)) }
        restoring.formUnion(restoredIDs)
        items = restored; removed.removeAll()
        guard save() else { items = oldItems; removed = oldRemoved; restoring = oldRestoring; return }
        pendingClears.remove(step.id)
        _ = persistUndo(nil)
        undoStep = nil; canUndo = false
        evicted.forEach(deleteImage)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.04) { [weak self] in
            guard let self else { return }
            withAnimation(.easeOut(duration: 0.24)) { self.restoring.subtract(restoredIDs) }
        }
    }
    func completeRemoval(_ id: UUID) {
        guard removed.contains(id) else { return }
        items.removeAll { $0.id == id }; removed.remove(id); itemFrames[id] = nil
    }
    @discardableResult private func save() -> Bool {
        do {
            let folder = file.deletingLastPathComponent()
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try JSONEncoder().encode(items.filter { !removed.contains($0.id) }).write(to: file, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            storageError = nil; return true
        } catch { storageError = "图文暂未保存：\(error.localizedDescription)"; return false }
    }
    func migratePicline() {
        guard !UserDefaults.standard.bool(forKey: "piclineMigrated") else { return }
        let paths = UserDefaults(suiteName: "local.captureline.preview")?.stringArray(forKey: "pegged") ?? []
        var succeeded = true
        for path in paths {
            if let data = try? Data(contentsOf: URL(fileURLWithPath: path)) {
                if !hangImage(data, notify: false) { succeeded = false }
            }
        }
        if succeeded { UserDefaults.standard.set(true, forKey: "piclineMigrated") }
    }
}
